export type DictKey = keyof typeof dict.ar;

export function t(lang: Language, key: DictKey): string {
  return dict[lang][key] ?? dict.ar[key] ?? key;
}

export function formatCurrency(amount: number, lang: Language): string {
  const formatted = new Intl.NumberFormat(
    lang === "ar" ? "ar-MA" : lang === "fr" ? "fr-MA" : "en-MA",
    { minimumFractionDigits: 2, maximumFractionDigits: 2 }
  ).format(amount);
  return lang === "ar" ? `${formatted} د.م` : `${formatted} MAD`;
}

export function formatDate(dateStr: string, lang: Language): string {
  if (!dateStr) return "";
  try {
    const date = new Date(dateStr);
    return new Intl.DateTimeFormat(
      lang === "ar" ? "ar-MA" : lang === "fr" ? "fr-FR" : "en-US",
      { year: "numeric", month: "long", day: "numeric" }
    ).format(date);
  } catch {
    return dateStr;
  }
}
